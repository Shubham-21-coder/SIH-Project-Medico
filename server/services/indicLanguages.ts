export function getLocalizedItem(key: string, lang: string = 'en'): LocalizedItem {
  const targetLang = (['en', 'hi', 'te', 'ta', 'bn', 'mr', 'gu', 'kn'].includes(lang) ? lang : 'en') as SupportedLanguage;
  const entry = INDIC_DICTIONARY[key];
  if (!entry) {
    return INDIC_DICTIONARY.general_greeting[targetLang];
  }
  return entry[targetLang] || entry.en;
}
